// Generates the extension's view of the status document from the JSON Schema that the types of
// wtpool-core produce (status-panel.md, S7): src/generated/status.schema.json, the TypeScript types
// status.d.ts and the ajv standalone validator validate.js with its declaration validate.d.ts.
//
//   node scripts/generate.mjs                       the schema from `cargo run --example status_schema`
//   node scripts/generate.mjs --schema-file <path>  the schema from a file
//
// The output depends only on the schema, so a second run rewrites nothing. A file whose content
// is unchanged is left alone, mtime included.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import Ajv from 'ajv';
import Ajv2019 from 'ajv/dist/2019.js';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';

const VSCODE = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const REPO = path.dirname(VSCODE);
const OUT = path.join(VSCODE, 'src', 'generated');
const ROOT_TYPE = 'StatusDocument';
const BANNER = 'Generated by `npm run generate` from the JSON Schema of wtpool-core. Do not edit.';

function readSchema(args) {
  if (args[0] === '--schema-file') {
    if (!args[1]) throw new Error('usage: generate.mjs [--schema-file <path>]');
    return readFileSync(args[1], 'utf8');
  }
  if (args.length) throw new Error('usage: generate.mjs [--schema-file <path>]');
  return execFileSync('cargo', ['run', '-q', '-p', 'wtpool-core', '--example', 'status_schema'], {
    cwd: REPO,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    maxBuffer: 16 * 1024 * 1024,
  });
}

/** The ajv class of the schema's draft. */
function ajvFor(schema) {
  const options = { code: { source: true, esm: true }, strict: true, validateFormats: false };
  const draft = String(schema.$schema ?? '');
  if (draft.includes('2020-12')) return new Ajv2020(options);
  if (draft.includes('2019-09')) return new Ajv2019(options);
  return new Ajv(options);
}

/** The TypeScript types. The root type is always StatusDocument, whatever the schema's title. */
async function types(schema) {
  const root = structuredClone(schema);
  delete root.title;
  delete root.$id;
  return compile(root, ROOT_TYPE, {
    bannerComment: `// ${BANNER}`,
    additionalProperties: false,
    unreachableDefinitions: false,
    strictIndexSignatures: true,
    $refOptions: { resolve: { external: false } },
  });
}

/** The standalone validator: an ES module exporting `validate`. */
function validator(schema) {
  const ajv = ajvFor(schema);
  const copy = structuredClone(schema);
  delete copy.$id;
  ajv.addSchema(copy, 'status');
  return `// ${BANNER}\n${standaloneCode(ajv, { validate: 'status' })}\n`;
}

const DECLARATION = `// ${BANNER}
import type { ${ROOT_TYPE} } from './status';

export interface ValidationError {
  instancePath: string;
  message?: string;
}

/** Whether \`data\` is a status document; on false, \`validate.errors\` says why. */
export declare const validate: {
  (data: unknown): data is ${ROOT_TYPE};
  errors?: ValidationError[] | null;
};
`;

function writeIfChanged(name, content) {
  const file = path.join(OUT, name);
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return;
  writeFileSync(file, content);
  process.stdout.write(`wrote src/generated/${name}\n`);
}

const schema = JSON.parse(readSchema(process.argv.slice(2)));
mkdirSync(OUT, { recursive: true });
writeIfChanged('status.schema.json', `${JSON.stringify(schema, null, 2)}\n`);
writeIfChanged('status.d.ts', await types(schema));
writeIfChanged('validate.js', validator(schema));
writeIfChanged('validate.d.ts', DECLARATION);
