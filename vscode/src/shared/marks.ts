/** A harness's mark and, where it is a maker's own, that maker. */
interface HarnessMark {
  /** The row that stands for the harness. */
  readonly mark: string;
  /** The row of the maker the harness belongs to; its models show no badge. */
  readonly maker?: string;
  /** The name the label of a mark shows for the harness. */
  readonly name: string;
}

const HARNESSES: ReadonlyMap<string, HarnessMark> = new Map([
  ['claude-code', { mark: 'anthropic', maker: 'anthropic', name: 'Claude Code' }],
  ['opencode', { mark: 'opencode', name: 'OpenCode' }],
]);

/** The marks one agent line shows. */
export interface ResolvedMark {
  /** The row of the line's mark. */
  readonly mark: string;
  /** The harness of the corner badge and the row of its mark, absent without a badge. */
  readonly badge?: { readonly harness: string; readonly mark: string };
}

function rowOf(id: string): MarkRow | undefined {
  return MARKS.find((row) => row.id === id);
}

/** Gives the row of the maker a model name belongs to, matching its parts from the last. */
function makerOf(model: string | null | undefined): MarkRow | undefined {
  if (!model) return undefined;
  for (const part of model.toLowerCase().split('/').reverse()) {
    const row = MARKS.find((candidate) =>
      candidate.prefixes.some((start) => part.startsWith(start)),
    );
    if (row) return row;
  }
  return undefined;
}

/**
 * Gives the marks of an agent of `harness` that runs `model`: the model maker's mark, badged with
 * the harness's unless the harness is the maker's own; else the harness's mark; else none.
 */
export function resolveMark(
  harness: string,
  model: string | null | undefined,
): ResolvedMark | null {
  const own = HARNESSES.get(harness);
  const harnessRow = own ? rowOf(own.mark) : undefined;
  const maker = makerOf(model);
  if (!maker) return harnessRow ? { mark: harnessRow.id } : null;
  if (!own || !harnessRow || own.maker === maker.id) return { mark: maker.id };
  return { mark: maker.id, badge: { harness, mark: harnessRow.id } };
}

/**
 * Gives the text of a mark's label: the last `/` part of the model, then the harness's display name,
 * or the harness alone for an actor with no model.
 */
export function markLabelText(harness: string, model: string | null | undefined): string {
  const name = HARNESSES.get(harness)?.name ?? harness;
  const shortModel = model?.split('/').at(-1);
  return shortModel ? `${shortModel} · ${name}` : name;
}
